import {test,afterEach} from 'node:test';
import assert from 'node:assert/strict';
import React from 'react';
import {JSDOM} from 'jsdom';
const dom=new JSDOM('<!doctype html><html><body></body></html>',{url:'http://localhost:4001'});
Object.assign(globalThis,{window:dom.window,document:dom.window.document,HTMLElement:dom.window.HTMLElement,HTMLInputElement:dom.window.HTMLInputElement,MutationObserver:dom.window.MutationObserver,IS_REACT_ACT_ENVIRONMENT:true});
const {render,screen,fireEvent,cleanup,waitFor}=await import('@testing-library/react');
const {StaticVaultConsole}=await import('../src/components/static-vault-console');
const originalFetch=globalThis.fetch;
afterEach(()=>{cleanup();globalThis.fetch=originalFetch;});
test('restores the familiar sidebar, tables and collapsed application/tenant details using v2 only',async()=>{
 const requests:string[]=[];
 globalThis.fetch=(async(input:any)=>{const url=new URL(String(input),'http://localhost:4001');requests.push(url.pathname);const path=url.pathname.replace('/api/vault-v2/','');let value:any=[];
 if(path==='catalog')value={applications:[{_id:'vault-app',displayName:'Vault APP',description:'Authentication console'},{_id:'club-api',displayName:'Club API',description:'Club business API'}],tenants:[{_id:'fcrww',displayName:'FCRWW'}],assignments:[{applicationId:'club-api',tenantId:'fcrww',enabled:true}],grants:[],instances:[]};
 else if(path==='access')value={canWrite:false,canRead:false,canExportKeys:false,canRotate:false};
 else if(path.startsWith('links/'))value={links:[],deployment:{revision:1}};
 else if(path==='resources')value=[{_id:'a',name:'Database access',kind:'secret',currentVersionId:'v1',currentVersionNumber:1,revision:1},{_id:'b',name:'Wrapping key',kind:'encryption-key',currentVersionId:'v1',currentVersionNumber:1,revision:1}];
 else if(path==='consent')value={enabled:false,canManage:false,revision:0};
 return Response.json(value)}) as typeof fetch;
 const{container}=render(<StaticVaultConsole account={<span>Account menu</span>}/>);
 assert.ok(container.querySelector('.app-shell .sidebar'));
 assert.ok(screen.getByRole('navigation',{name:'Vault sections'}));
 for(const name of ['Runtime configuration','Applications','Keys','Secrets'])assert.ok(screen.getByRole('button',{name}));
 await waitFor(()=>assert.ok(screen.getByRole('button',{name:'Expand tenant fcrww'})));
 assert.equal(screen.queryByLabelText('Search key'),null);
 fireEvent.click(screen.getByRole('button',{name:'Applications'}));
 await waitFor(()=>assert.ok(screen.getByText('Club business API')));
 assert.ok(screen.getByRole('checkbox',{name:'Vault APP'}));
 assert.equal(screen.queryByLabelText('Search key'),null);
 fireEvent.click(screen.getByRole('button',{name:'Expand Club API'}));
 await waitFor(()=>assert.ok(screen.getByLabelText('Search key')));
 fireEvent.click(screen.getByRole('button',{name:'Collapse Club API'}));
 assert.equal(screen.queryByLabelText('Search key'),null);
 fireEvent.click(screen.getByRole('button',{name:'Keys'}));
 await waitFor(()=>assert.ok(screen.getAllByText('Wrapping key').length));
 assert.equal(screen.queryByText('Database access'),null);
 fireEvent.click(screen.getByRole('button',{name:'Secrets'}));
 await waitFor(()=>assert.ok(screen.getAllByText('Database access').length));
 assert.equal(screen.queryByText('Wrapping key'),null);
 fireEvent.click(screen.getByRole('button',{name:'Runtime configuration'}));
 await waitFor(()=>assert.ok(screen.getByRole('button',{name:'Expand tenant fcrww'})));
 assert.equal(screen.queryByLabelText('Search key'),null);
 fireEvent.click(screen.getByRole('button',{name:'Expand tenant fcrww'}));
 await waitFor(()=>assert.ok(screen.getByLabelText('Consuming application')));
 assert.equal(screen.getByRole('button',{name:'Collapse tenant fcrww'}).getAttribute('aria-expanded'),'true');
 fireEvent.click(screen.getByRole('button',{name:'Collapse tenant fcrww'}));
 assert.equal(screen.queryByLabelText('Search key'),null);
 assert.ok(requests.length>0&&requests.every(path=>path.startsWith('/api/vault-v2/')));
});
